export function translateDOM(root, language = "ar") {
  if (!root || language === "ar") return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (node.parentElement?.closest("[data-no-translate],.tx-title,.tx-category,.category-name,.category-manage-name,.budget-name,script,style")) continue;
    const original = node.nodeValue;
    const trimmed = original.trim();
    const dayOption = trimmed.match(/^يوم (\d+) من كل شهر$/);
    const translated = dayOption
      ? language === "ar" ? trimmed : language === "en" ? `Day ${dayOption[1]} of each month` : `Her ayın ${dayOption[1]}. günü`
      : translate(trimmed, language);
    if (translated !== trimmed) node.nodeValue = original.replace(trimmed, translated);
  }
  for (const element of root.querySelectorAll("[placeholder],[aria-label],[title]")) {
    for (const attribute of ["placeholder", "aria-label", "title"]) {
      if (!element.hasAttribute(attribute)) continue;
      const original = element.getAttribute(attribute);
      const dynamicAction = original.match(/^(تعديل|حذف) (.+)$/);
      const translated = dynamicAction
        ? `${translate(dynamicAction[1], language)} ${dynamicAction[2]}`
        : translate(original, language);
      if (translated !== original) element.setAttribute(attribute, translated);
    }
  }
}
